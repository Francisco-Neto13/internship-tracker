const relatorioNaoEncontrado = () =>
  new DomainError({ code: "RELATORIO_NAO_ENCONTRADO", kind: "NOT_FOUND", message: "Relatório não encontrado.", requisito: "RF037" });

async function carregarRelatorio(tx: Transaction, id: string): Promise<RelatorioRow> {
  const relatorio = await findRelatorioById(tx, id);
  if (!relatorio) throw relatorioNaoEncontrado();
  return relatorio;
}

function comSituacaoExibida(relatorio: RelatorioRow, diaAtual: string) {
  return { ...relatorio, emAtraso: relatorioEmAtraso(relatorio, diaAtual), pendenteDe: pendenteDe(relatorio.situacao) };
}

/** RF037, RF040: reports owed by the internship, with deadlines and the derived lateness. */
export async function listRelatorios(identity: Identity, estagioId: string) {
  return withUser(identity, async (tx) => {
    await carregarEstagioAcompanhado(tx, estagioId);
    if (!(await podeLerRelatorios(tx, estagioId))) throw acessoNegado("ler os relatórios deste estágio");
    const diaAtual = await hoje(tx);
    return (await findRelatorios(tx, estagioId)).map((relatorio) => comSituacaoExibida(relatorio, diaAtual));
  });
}

/** RF039: the report with every version, its attachments and opinions (history kept). */
export async function getRelatorio(identity: Identity, id: string) {
  return withUser(identity, async (tx) => {
    const relatorio = await carregarRelatorio(tx, id);
    const diaAtual = await hoje(tx);
    const versoes = await findVersoes(tx, id);
    const ids = versoes.map((versao) => versao.id);
    const [anexos, pareceres] = [await findAnexos(tx, ids), await findPareceres(tx, ids)];
    return {
      relatorio: comSituacaoExibida(relatorio, diaAtual),
      versoes: versoes.map((versao) => ({
        ...versao,
        enviadaComAtraso: enviadoComAtraso(relatorio.prazoEntrega, versao.enviadoEmLocal),
        anexos: anexos.filter((anexo) => anexo.versaoRelatorioId === versao.id),
        parecer: pareceres.find((parecer) => parecer.versaoRelatorioId === versao.id) ?? null,
      })),
    };
  });
}

/** RF037 to RF039: the report as a PDF, for whoever reads it; a report not yet sent has no document. */
export async function pdfRelatorio(identity: Identity, id: string): Promise<Uint8Array> {
  const { relatorio, versoes } = await getRelatorio(identity, id);
  if (versoes.length === 0) {
    throw new DomainError({ code: "RELATORIO_NAO_ENVIADO", kind: "NOT_FOUND", message: "O relatório ainda não foi enviado.", requisito: "RF037" });
  }
  const { identificacao } = await getEstagioDetalhado(identity, relatorio.estagioId);
  return gerarPdfDocumento(documentoRelatorio(relatorio, versoes, identificacao));
}

/**
 * RF037, RF039, RF041: the student sends the report (first time or after a return) with text
 * and/or attachments already uploaded (D8). Late sending is accepted and shown as late.
 */
export async function enviarRelatorio(identity: Identity, relatorioId: string, input: { conteudo: string | null; documentoIds: string[] }) {
  if (identity.titularId) throw relatorioForaDaTroca("enviar");
  const conteudo = input.conteudo?.trim() || null;
  if (!conteudo && input.documentoIds.length === 0) {
    throw new DomainError({ code: "RELATORIO_VAZIO", kind: "UNPROCESSABLE", message: "O relatório precisa de texto ou de ao menos um anexo.", requisito: "RF037" });
  }
  const estagioId = await withUser(identity, async (tx) => (await carregarRelatorio(tx, relatorioId)).estagioId);
  for (const documentoId of new Set(input.documentoIds)) {
    await exigirDocumento(identity, documentoId, { tipo: "RELATORIO", estagioId });
  }
  try {
    return await withUser(identity, async (tx) => {
      const relatorio = await carregarRelatorio(tx, relatorioId);
      if (relatorio.situacao !== "PENDENTE" && relatorio.situacao !== "DEVOLVIDO") {
        throw new DomainError({
          code: "RELATORIO_NAO_ENVIAVEL",
          kind: "CONFLICT",
          message: relatorio.situacao === "EM_ANALISE" ? "O relatório já está em análise pelo orientador." : "O relatório já foi aprovado.",
          requisito: "RF037",
        });
      }
      const versao = await insertVersao(tx, { relatorioId, conteudo, enviadoPorUsuarioId: identity.userId });
      await insertAnexos(tx, versao.id, [...new Set(input.documentoIds)]);
      return versao;
    });
  } catch (error) {
    throw traduzir(error, "enviar o relatório");
  }
}

/**
 * RF003, RN-38: the administrator acting as another account does not read report content, so it
 * neither sends nor decides one. The policies of versao_relatorio and parecer_relatorio refuse it
 * too; this only says why, instead of a version that seems missing.
 */
function relatorioForaDaTroca(acao: "enviar" | "analisar") {
  return new DomainError({
    code: "CONTEXTO_SEM_RELATORIO",
    kind: "FORBIDDEN",
    message: `O administrador não lê relatórios, então não pode ${acao} um relatório pela troca de perfil.`,
    requisito: "RF003",
  });
}

/**
 * RF038, RN-14: the advisor approves (opinion optional) or returns (opinion required) the
 * latest version; the date and time of the decision are recorded (RN-28).
 */
export async function decidirRelatorio(identity: Identity, relatorioId: string, decisao: "APROVADO" | "DEVOLVIDO", texto: string | null) {
  if (identity.titularId) throw relatorioForaDaTroca("analisar");
  const parecer = texto?.trim() || null;
  if (decisao === "DEVOLVIDO" && !parecer) {
    throw new DomainError({ code: "PARECER_OBRIGATORIO", kind: "UNPROCESSABLE", message: "A devolução exige parecer.", requisito: "RF038" });
  }
  try {
    return await withUser(identity, async (tx) => {
      const relatorio = await carregarRelatorio(tx, relatorioId);
      const [ultima] = await findVersoes(tx, relatorioId);
      if (relatorio.situacao !== "EM_ANALISE" || !ultima) {
        throw new DomainError({ code: "RELATORIO_NAO_ANALISAVEL", kind: "CONFLICT", message: "O relatório não está em análise.", requisito: "RF038" });
      }
      return insertParecer(tx, { versaoRelatorioId: ultima.id, decisao, texto: parecer, emitidoPorUsuarioId: identity.userId });
    });
  } catch (error) {
    throw traduzir(error, "analisar o relatório");
  }
}

/**
 * RF040: what is waiting now. A report is due once its period has ended (the final one, once
 * the internship's planned end has passed); in analysis, it waits for the advisor. Notifying
 * student and advisor (RF040, priority I) is the Fase 5 hook that reads this same list.
 */
export async function listRelatoriosPendentes(identity: Identity) {
  return withUser(identity, async (tx) => {
    const diaAtual = await hoje(tx);
    return (await findRelatoriosEmAberto(tx))
      .filter(({ relatorio }) => relatorio.situacao === "EM_ANALISE" || (relatorio.periodoFim !== null && relatorio.periodoFim < diaAtual))
      .map(({ relatorio, estudanteNome }) => ({ ...comSituacaoExibida(relatorio, diaAtual), estudanteNome }));
  });
}

/** RF040, RNF-11: one page of the same list for the screen, with the total of each view. */
export async function listRelatoriosPendentesPagina(identity: Identity, query: { visao: VisaoRelatorio; page: number; limit: number }) {
  return withUser(identity, async (tx) => {
    const diaAtual = await hoje(tx);
    const linhas = await findRelatoriosPendentesPagina(tx, diaAtual, query.visao, query.limit, (query.page - 1) * query.limit);
    const contagens = await countRelatoriosPendentes(tx, diaAtual);
    return { items: linhas.map(({ relatorio, estudanteNome }) => ({ ...comSituacaoExibida(relatorio, diaAtual), estudanteNome })), total: contagens[query.visao], contagens };
  });
}
